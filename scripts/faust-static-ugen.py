"""Turn the Faust SuperCollider UGen source into a statically linked plugin.

Faust's supercollider.cpp architecture makes a plugin for dlopen: it exports
`load`, `api_version` and `server_type`, and it names its unit struct and its
unit functions `Faust`, `Faust_Ctor` and so on. A static build links all
plugins into one binary, and these names then collide between two Faust UGens.

This script renames them, so that each UGen has its own names, and removes
the three exported functions. The entry point becomes `<Name>_Load`. The
host calls this function from its plugin initialisation (in scsynth:
SC_Lib_Cintf.cpp). build-sc-static.py runs this script for each UGen.

The script also makes the UGen agree with SuperSonic, where one process can
have more than one engine (World) and each World has its own copy of the
interface table. The changes apply only when CLOCKWORK_GUEST is defined
(SuperSonic's engine); with stock scsynth headers the code stays as Faust made
it:
  - `ft` points to SuperSonic's constant table (gInterfaceTable). The table
    that the load function gets belongs to one World and goes away with it.
  - The load function registers the UGen through its own table argument
    (`DefineUnit`), in the World that loads it.
  - A print in the load function names the World that loads it.

Usage:
    faust -a supercollider.cpp -cn <Name> -ftz 1 -I <lib dir> <sketch>.dsp \
        -o raw.cpp
    faust-static-ugen.py <Name> raw.cpp <out>.cpp

<Name> must be the same as the class name given to Faust with -cn.
"""
import re
import sys


def convert(name: str, source: str) -> str:
    unit = f"{name}Unit"

    # The unit struct and its functions. The \b stops a match inside longer
    # words, and `Faust_` does not match the Faust library macros.
    source = re.sub(r"\bFaust_(\w+)", rf"{name}_\1", source)
    source = re.sub(r"\bstruct Faust\b", f"struct {unit}", source)
    source = re.sub(r"\bFaust\*", f"{unit}*", source)
    source = re.sub(r"sizeof\(Faust\)", f"sizeof({unit})", source)

    # The entry point.
    source, count = re.subn(
        r"FAUST_EXPORT void load\(InterfaceTable\*(\s*\w+)?\)",
        lambda m: f"void {name}_Load(InterfaceTable*{m.group(1) or ''})",
        source,
    )
    if count != 2:
        sys.exit(f"expected 2 load() lines (declaration and definition), found {count}")

    # api_version is exported only when SC_API_EXPORT is set. Remove the
    # declaration and the definition, each with its #ifdef guard.
    source = re.sub(
        r"#ifdef SC_API_EXPORT\n\s*FAUST_EXPORT int api_version\(void\)[^\n]*\n#endif\n",
        "",
        source,
    )

    # server_type tells the host if this is a scsynth or a supernova plugin.
    # A static plugin has no use for it.
    source = re.sub(
        r"#ifdef SUPERNOVA\s*\nextern \"C\" FAUST_EXPORT int server_type\(void\)[^\n]*\n"
        r"#else\s*\nextern \"C\" FAUST_EXPORT int server_type\(void\)[^\n]*\n#endif\n",
        "",
        source,
    )

    for leftover in ("api_version", "server_type"):
        if re.search(rf"\b{leftover}\b", source):
            sys.exit(f"{leftover} is still in the output: the architecture file changed")

    source = plural_guest(name, source)

    banner = (
        "// Generated by scripts/faust-static-ugen.py from Faust output. Do not edit.\n"
        "// To change the UGen, change the .dsp sketch and generate again.\n"
    )
    return banner + source


def replace_once(source: str, old: str, new: str) -> str:
    """Replaces the one occurrence of old. Stops if there is not exactly one:
    then the architecture file changed."""
    count = source.count(old)
    if count != 1:
        sys.exit(f"expected 1 {old.strip()!r}, found {count}: the architecture file changed")
    return source.replace(old, new)


def plural_guest(name: str, source: str) -> str:
    """Makes the UGen agree with SuperSonic's engines (see the module text)."""
    source = replace_once(
        source,
        "static InterfaceTable* ft;\n",
        "#ifdef CLOCKWORK_GUEST\n"
        "// SuperSonic: the engine's functions come from the one constant table.\n"
        "// The table that the load function gets belongs to one World and goes\n"
        "// away with it, so the plugin does not keep it.\n"
        "static const InterfaceTable* const ft = &gInterfaceTable;\n"
        "// A print in the load function names the World that loads the plugin.\n"
        "#define LoadPrint(...) (*ft->fPrint)(inTable->mWorld, __VA_ARGS__)\n"
        "#else\n"
        "static InterfaceTable* ft;\n"
        "#define LoadPrint Print\n"
        "#endif\n",
    )

    # The body of the load function, from its definition to the first line
    # that is only a closing brace.
    head = f"void {name}_Load(InterfaceTable* inTable)\n{{\n"
    start = source.find(head)
    end = source.find("\n}\n", start)
    if start < 0 or end < 0:
        sys.exit(f"the definition of {name}_Load is not in the output: the architecture file changed")
    body = source[start:end]

    body = replace_once(
        body,
        "    ft = inTable;\n",
        "#ifndef CLOCKWORK_GUEST\n    ft = inTable;\n#endif\n",
    )
    # The DefineUnit macro registers through inTable in SuperSonic and
    # through ft with stock scsynth headers.
    body = replace_once(body, "(*ft->fDefineUnit)(", "DefineUnit(")
    body = re.sub(r"\bPrint\(", "LoadPrint(", body)

    return source[:start] + body + source[end:]


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    name, src, dst = sys.argv[1:]
    with open(src) as f:
        text = f.read()
    with open(dst, "w") as f:
        f.write(convert(name, text))


if __name__ == "__main__":
    main()
