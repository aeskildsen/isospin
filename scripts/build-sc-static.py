"""Make the static SuperCollider UGen sources from the Faust instruments.

A static UGen is linked into the server binary, as SuperSonic needs; it is
not a plugin that the server loads at run time. The UGens are listed in
supercollider.toml. For each UGen, this script runs faust with the
supercollider.cpp architecture and then faust-static-ugen.py. The output
folder gets:

    src/<class>.cpp         the UGen sources
    classes/<unit>.sc       the SuperCollider class files, for sclang
    include/faust/...       the Faust headers that the sources include
    isospin.cmake           the source list and build settings, for CMake
    isospin_sc_static.h     the load declarations and Isospin_Load()
    BUILDINFO               the kind of build, version, commit, Faust version
    LICENSE, NOTICE.md      the licences

Usage:
    build-sc-static.py --out DIR
        Development build into DIR. Writes only the files that changed, so
        that a build system compiles only the changed UGens.
    build-sc-static.py --release VERSION --tarball DIR
        Release build. The working tree must be clean. Writes
        isospin-sc-static-VERSION.tar.gz and its .sha256 file into DIR. The
        same commit and the same Faust version give the same bytes.

Needs faust on PATH (the Faust version is in BUILDINFO).
"""
import argparse
import gzip
import hashlib
import importlib.util
import io
import json
import shutil
import subprocess
import sys
import tarfile
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The Faust headers that the supercollider.cpp architecture includes. They are
# copied without change from the Faust installation.
FAUST_HEADERS = [
    "faust/dsp/dsp.h",
    "faust/export.h",
    "faust/gui/UI.h",
    "faust/gui/meta.h",
    "faust/misc.h",
]

GENERATED = "Generated by isospin scripts/build-sc-static.py. Do not edit."


def load_rewrite():
    # Load faust-static-ugen.py by path: python -I does not put the script
    # folder on sys.path.
    # Write no __pycache__ folder: it would make the working tree unclean.
    sys.dont_write_bytecode = True
    path = ROOT / "scripts" / "faust-static-ugen.py"
    spec = importlib.util.spec_from_file_location("faust_static_ugen", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run(*args: str) -> str:
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def git(*args: str) -> str:
    return run("git", "-C", str(ROOT), *args).strip()


def read_ugens() -> list[dict]:
    with open(ROOT / "supercollider.toml", "rb") as f:
        ugens = tomllib.load(f)["ugen"]
    for ugen in ugens:
        for key in ("dsp", "class", "prefix"):
            if not isinstance(ugen.get(key), str) or not ugen[key]:
                sys.exit(f"supercollider.toml: each [[ugen]] needs a {key} string")
    return ugens


def cmake_file(ugens: list[dict], label: str) -> str:
    lines = [
        f"# {GENERATED}",
        f"# The static SuperCollider UGens of isospin {label}.",
        "#",
        "# Include this file from the CMake folder that builds the server, then",
        "# add ISOSPIN_SC_STATIC_SOURCES to the plugin sources and call",
        "# Isospin_Load() from isospin_sc_static.h. The source properties apply in",
        "# the folder that includes this file.",
        "",
        'set(ISOSPIN_SC_STATIC_DIR "${CMAKE_CURRENT_LIST_DIR}")',
        "set(ISOSPIN_SC_STATIC_SOURCES",
    ]
    lines += [f'    "${{ISOSPIN_SC_STATIC_DIR}}/src/{u["class"]}.cpp"' for u in ugens]
    lines[-1] += ")"
    for u in ugens:
        lines += [
            f'set_source_files_properties("${{ISOSPIN_SC_STATIC_DIR}}/src/{u["class"]}.cpp" PROPERTIES',
            '    INCLUDE_DIRECTORIES "${ISOSPIN_SC_STATIC_DIR}/include"',
            f'    COMPILE_DEFINITIONS "SC_FAUST_PREFIX=\\"{u["prefix"]}\\"")',
        ]
    return "\n".join(lines) + "\n"


def header_file(ugens: list[dict], label: str) -> str:
    lines = [
        f"// {GENERATED}",
        f"// The load functions of the static SuperCollider UGens of isospin {label}.",
        "// Call Isospin_Load() once from the server's plugin initialisation.",
        "#pragma once",
        "",
        "struct InterfaceTable;",
        "",
        "// The Faust supercollider.cpp architecture declares the load functions",
        "// with C linkage.",
        'extern "C" {',
    ]
    lines += [f"void {u['class']}_Load(InterfaceTable* table);" for u in ugens]
    lines += ["}", "", "static inline void Isospin_Load(InterfaceTable* table) {"]
    lines += [f"    {u['class']}_Load(table);" for u in ugens]
    lines += ["}"]
    return "\n".join(lines) + "\n"


def normalize_name(name: str) -> str:
    """The unit name that the supercollider.cpp architecture makes from the
    Faust name: each word capitalised, without "_", "-" and " ", at most 30
    characters (the same as normalizeClassName in supercollider.cpp)."""
    out, up = "", True
    for char in name:
        if char in "_- ":
            up = True
        elif up:
            out, up = out + char.upper(), False
        else:
            out += char
    return out[:30]


def sc_number(value: float) -> str:
    """A number in sclang syntax, without a ".0" on whole numbers."""
    value = float(value)
    return str(int(value)) if value.is_integer() else repr(value)


def sc_argument(label: str) -> str:
    """The class argument name for a Faust control label (the same rule as
    faust2sc.py): without the characters "\\-_/()[]^", in lower case,
    spaces as "_"."""
    for char in "\\-_/([^)]*)":
        label = label.replace(char, "")
    return label.lower().replace(" ", "_")


def class_file(info: dict, prefix: str) -> tuple[str, str]:
    """The unit name and the SuperCollider class file for one UGen, from the
    Faust JSON description. The class arguments are the audio inputs
    (in0, in1, ...) and then the controls, in the order of the JSON file.
    This is the order in which the UGen reads its inputs."""
    unit = (prefix + normalize_name(info["name"]))[:30]
    (group,) = info["ui"]
    controls = []
    for item in group["items"]:
        if "items" in item:
            sys.exit(f"{info['name']}: a UI group in a group is not supported; "
                     "make the controls of the top group flat")
        controls.append((sc_argument(item["label"]), sc_number(item.get("init", 0))))
    inputs = [f"in{i}" for i in range(info["inputs"])]
    names = ", ".join(inputs + [name for name, _ in controls])
    args = ", ".join(inputs + [f"{name}({default})" for name, default in controls])
    outputs = info["outputs"]

    lines = [
        f"// {GENERATED}",
        f"// The class of the {unit} UGen, made from the Faust description of",
        f"// {info['filename']}.",
        f"{unit} : {'MultiOutUGen' if outputs > 1 else 'UGen'} {{",
        f"    *ar {{ |{args}|",
        f"        ^this.multiNew('audio', {names})",
        "    }",
        "",
        f"    *kr {{ |{args}|",
        f"        ^this.multiNew('control', {names})",
        "    }",
        "",
        f'    name {{ ^"{unit}" }}',
        "",
        '    info { ^"Generated with Faust" }',
    ]
    if info["inputs"] > 0:
        lines += [
            "",
            "    checkInputs {",
            "        if(rate == 'audio') {",
            f"            {info['inputs']}.do {{ |i|",
            "                if(inputs.at(i).rate != 'audio') {",
            "                    ^(\" input at index \" ++ i ++ \" (\" ++ inputs.at(i) ++ \") is not audio rate\")",
            "                };",
            "            };",
            "        };",
            "        ^this.checkValidInputs",
            "    }",
        ]
    if outputs > 1:
        lines += [
            "",
            "    init { |... theInputs|",
            "        inputs = theInputs;",
            f"        ^this.initOutputs({outputs}, rate)",
            "    }",
        ]
    lines += ["}"]
    return unit, "\n".join(lines) + "\n"


NOTICE = """\
# isospin: static SuperCollider UGen sources

{generated}

Made from the Faust sources of isospin (https://github.com/aeskildsen/isospin),
{label}. BUILDINFO gives the commit and the Faust version.

## UGens

{ugens}

## Licences

- As a whole: AGPL-3.0-or-later (see LICENSE). Copyright (C) 2026 Anders
  Eskildsen.
- `src/*.cpp` combine code made from the AGPL-3.0-or-later Faust sources with
  the Faust `supercollider.cpp` architecture, which is GPL-3.0-or-later. The
  architecture has an exception for unchanged use, but the static rewrite
  (`faust-static-ugen.py`) changes it, so the exception does not apply here.
  Section 13 of the GPL-3.0 and of the AGPL-3.0 lets the two parts be
  combined. Each file says which section has which licence.
- `include/faust/*`: copied without change from Faust (GRAME). They are
  LGPL-2.1-or-later with the Faust architecture exception (see each file). Do
  not change them; copy them again from a new Faust version instead.
"""


def generate(dest: Path, label: str, kind: str) -> None:
    """Writes the full output into dest, which must be empty."""
    rewrite = load_rewrite()
    ugens = read_ugens()
    include_dir = Path(run("faust", "--includedir").strip())
    faust_version = run("faust", "--version").splitlines()[0].strip()

    with tempfile.TemporaryDirectory() as tmp:
        for u in ugens:
            raw = Path(tmp) / f"{u['class']}-raw.cpp"
            run("faust", "-a", "supercollider.cpp", "-cn", u["class"], "-ftz", "1",
                "-I", str(ROOT), str(ROOT / u["dsp"]), "-o", str(raw))
            out = dest / "src" / f"{u['class']}.cpp"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(rewrite.convert(u["class"], raw.read_text()))

            # A second faust call for the JSON description, so that the C++
            # call stays the same as before.
            run("faust", "-json", "-O", tmp, "-o", f"{u['class']}-json.cpp",
                "-I", str(ROOT), str(ROOT / u["dsp"]))
            info = json.loads((Path(tmp) / f"{Path(u['dsp']).name}.json").read_text())
            unit, text = class_file(info, u["prefix"])
            out = dest / "classes" / f"{unit}.sc"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text)

    for header in FAUST_HEADERS:
        out = dest / "include" / header
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(include_dir / header, out)

    commit = git("rev-parse", "HEAD")
    if git("status", "--porcelain"):
        commit += "-dirty"
    (dest / "isospin.cmake").write_text(cmake_file(ugens, label))
    (dest / "isospin_sc_static.h").write_text(header_file(ugens, label))
    (dest / "BUILDINFO").write_text(
        f"kind={kind}\nversion={label}\ncommit={commit}\nfaust={faust_version}\n")
    shutil.copyfile(ROOT / "LICENSE", dest / "LICENSE")
    listing = "\n".join(f"- `{u['dsp']}`: `src/{u['class']}.cpp`, prefix `{u['prefix']}`"
                        for u in ugens)
    listing += "\n\nThe SuperCollider class files are in `classes/`."
    (dest / "NOTICE.md").write_text(
        NOTICE.format(generated=GENERATED, label=label, ugens=listing))


def sync(src: Path, dest: Path) -> None:
    """Makes dest the same as src. Leaves unchanged files untouched."""
    dest.mkdir(parents=True, exist_ok=True)
    wanted = {p.relative_to(src) for p in src.rglob("*") if p.is_file()}
    for rel in sorted(wanted):
        target = dest / rel
        data = (src / rel).read_bytes()
        if target.is_file() and target.read_bytes() == data:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    for p in sorted(dest.rglob("*"), reverse=True):
        rel = p.relative_to(dest)
        if p.is_file() and rel not in wanted:
            p.unlink()
        elif p.is_dir() and not any(p.iterdir()):
            p.rmdir()


def pack(src: Path, tarball: Path, top: str) -> None:
    """Writes a tarball with fixed owners, modes and times, so that the same
    input gives the same bytes."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.PAX_FORMAT) as tar:
        def add(name: str, path: Path | None) -> None:
            info = tarfile.TarInfo(name)
            info.mtime = 0
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            if path is None:
                info.type = tarfile.DIRTYPE
                info.mode = 0o755
                tar.addfile(info)
            else:
                data = path.read_bytes()
                info.mode = 0o644
                info.size = len(data)
                tar.addfile(info, io.BytesIO(data))

        add(top, None)
        for p in sorted(src.rglob("*")):
            name = f"{top}/{p.relative_to(src).as_posix()}"
            add(name, None if p.is_dir() else p)
    with open(tarball, "wb") as f:
        with gzip.GzipFile(filename="", mode="wb", fileobj=f, mtime=0) as gz:
            gz.write(buf.getvalue())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--out", type=Path, help="development build into this folder")
    group.add_argument("--tarball", type=Path, help="release tarball into this folder")
    parser.add_argument("--release", metavar="VERSION", help="release version, for example 0.1.0")
    args = parser.parse_args()

    if args.tarball and not args.release:
        parser.error("--tarball needs --release VERSION")
    if args.out and args.release:
        parser.error("--release goes with --tarball, not --out")

    with tempfile.TemporaryDirectory() as tmp:
        staged = Path(tmp) / "out"
        staged.mkdir()
        if args.out:
            generate(staged, "development build", "development")
            sync(staged, args.out)
            print(f"build-sc-static: development build in {args.out}")
            return

        if git("status", "--porcelain"):
            sys.exit("build-sc-static: the working tree is not clean; a release needs a commit")
        generate(staged, args.release, "release")
        top = f"isospin-sc-static-{args.release}"
        args.tarball.mkdir(parents=True, exist_ok=True)
        tarball = args.tarball / f"{top}.tar.gz"
        pack(staged, tarball, top)
        digest = hashlib.sha256(tarball.read_bytes()).hexdigest()
        (args.tarball / f"{top}.tar.gz.sha256").write_text(f"{digest}  {tarball.name}\n")
        print(f"build-sc-static: {tarball}")
        print(f"sha256 {digest}")


if __name__ == "__main__":
    main()
