"""Make the static SuperCollider UGen sources from the Faust instruments.

A static UGen is linked into the server binary, as SuperSonic needs; it is
not a plugin that the server loads at run time. The UGens are listed in
supercollider.toml. For each Faust UGen ([[ugen]]), this script runs faust
with the supercollider.cpp architecture and then faust-static-ugen.py. A
hand-written C++ UGen ([[native]]) is copied without change. The output
folder gets:

    src/<class>.cpp         the Faust UGen sources
    src/<name>/...          the sources and headers of each hand-written UGen
    classes/<unit>.sc       the SuperCollider class files, for sclang
    include/faust/...       the Faust headers that the sources include
    include/isospin/...     the isospin header for hand-written UGens (only
                            when there is one)
    isospin.cmake           the source list and build settings, for CMake
    isospin_sc_static.h     the load declarations and Isospin_Load()
    BUILDINFO               the kind of build, version, commit, Faust version
    LICENSE, NOTICE.md      the licences

Usage:
    build-sc-static.py --out DIR [--manifest FILE]
        Development build into DIR. Writes only the files that changed, so
        that a build system compiles only the changed UGens. --manifest
        gives a different UGen list (default: supercollider.toml); the build
        checks use it for their test UGens.
    build-sc-static.py --release VERSION --tarball DIR
        Release build. The working tree must be clean. Writes
        isospin-sc-static-VERSION.tar.gz and its .sha256 file into DIR. The
        same commit and the same Faust version give the same bytes.

Needs faust on PATH (the Faust version is in BUILDINFO).
"""
import argparse
import gzip
import hashlib
import importlib.util
import io
import json
import shutil
import subprocess
import sys
import tarfile
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The Faust headers that the supercollider.cpp architecture includes. They are
# copied without change from the Faust installation.
FAUST_HEADERS = [
    "faust/dsp/dsp.h",
    "faust/export.h",
    "faust/gui/UI.h",
    "faust/gui/meta.h",
    "faust/misc.h",
]

GENERATED = "Generated by isospin scripts/build-sc-static.py. Do not edit."

# The header that each hand-written UGen includes (see the file).
NATIVE_HEADERS = ["isospin/sc_plugin_table.h"]

# The files of a hand-written UGen folder that the output gets, besides the
# sources in `core` and `plugin`: the headers. Files in its test/ folder are
# for the build checks only.
NATIVE_HEADER_SUFFIXES = (".h", ".hpp")


def load_rewrite():
    # Load faust-static-ugen.py by path: python -I does not put the script
    # folder on sys.path.
    # Write no __pycache__ folder: it would make the working tree unclean.
    sys.dont_write_bytecode = True
    path = ROOT / "scripts" / "faust-static-ugen.py"
    spec = importlib.util.spec_from_file_location("faust_static_ugen", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run(*args: str) -> str:
    return subprocess.run(args, check=True, capture_output=True, text=True).stdout


def git(*args: str) -> str:
    return run("git", "-C", str(ROOT), *args).strip()


def read_manifest(path: Path) -> tuple[list[dict], list[dict]]:
    """The Faust UGens ([[ugen]]) and the hand-written UGens ([[native]]) of
    a UGen list. Paths in the list are relative to the repository root."""
    with open(path, "rb") as f:
        data = tomllib.load(f)
    ugens = data.get("ugen", [])
    natives = data.get("native", [])
    for ugen in ugens:
        for key in ("dsp", "class", "prefix"):
            if not isinstance(ugen.get(key), str) or not ugen[key]:
                sys.exit(f"{path.name}: each [[ugen]] needs a {key} string")
    names = [u["class"] for u in ugens]
    for native in natives:
        for key in ("name", "dir", "load"):
            if not isinstance(native.get(key), str) or not native[key]:
                sys.exit(f"{path.name}: each [[native]] needs a {key} string")
        name = native["name"]
        for key in ("core", "plugin", "classes", "tests"):
            value = native.setdefault(key, [])
            if not isinstance(value, list) or not all(isinstance(v, str) and v for v in value):
                sys.exit(f"{path.name}: [[native]] {name}: {key} must be a list of paths")
        if not native["plugin"]:
            sys.exit(f"{path.name}: [[native]] {name}: plugin needs at least one source")
        folder = ROOT / native["dir"]
        for key in ("core", "plugin", "classes", "tests"):
            for rel in native[key]:
                if not (folder / rel).is_file():
                    sys.exit(f"{path.name}: [[native]] {name}: no file {native['dir']}/{rel}")
        for rel in native["core"] + native["plugin"]:
            if Path(rel).parts[0] == "test":
                sys.exit(f"{path.name}: [[native]] {name}: {rel}: the test/ folder is for tests only")
        names.append(name)
    if len(set(names)) != len(names):
        sys.exit(f"{path.name}: two UGens have the same class or name")
    return ugens, natives


def native_sources(native: dict) -> list[str]:
    """The sources of a hand-written UGen, relative to its folder."""
    return native["core"] + native["plugin"]


def native_files(native: dict) -> list[str]:
    """All files of a hand-written UGen that the output gets in src/<name>/:
    its sources and the headers of its folder, without the test/ folder."""
    folder = ROOT / native["dir"]
    headers = sorted(p.relative_to(folder).as_posix() for p in folder.rglob("*")
                     if p.is_file() and p.suffix in NATIVE_HEADER_SUFFIXES
                     and p.relative_to(folder).parts[0] != "test")
    return native_sources(native) + headers


def cmake_file(ugens: list[dict], natives: list[dict], label: str) -> str:
    lines = [
        f"# {GENERATED}",
        f"# The static SuperCollider UGens of isospin {label}.",
        "#",
        "# Include this file from the CMake folder that builds the server, then",
        "# add ISOSPIN_SC_STATIC_SOURCES to the plugin sources and call",
        "# Isospin_Load() from isospin_sc_static.h. The source properties apply in",
        "# the folder that includes this file.",
        "",
        'set(ISOSPIN_SC_STATIC_DIR "${CMAKE_CURRENT_LIST_DIR}")',
        "set(ISOSPIN_SC_STATIC_SOURCES",
    ]
    lines += [f'    "${{ISOSPIN_SC_STATIC_DIR}}/src/{u["class"]}.cpp"' for u in ugens]
    lines += [f'    "${{ISOSPIN_SC_STATIC_DIR}}/src/{n["name"]}/{rel}"'
              for n in natives for rel in native_sources(n)]
    lines[-1] += ")"
    for u in ugens:
        lines += [
            f'set_source_files_properties("${{ISOSPIN_SC_STATIC_DIR}}/src/{u["class"]}.cpp" PROPERTIES',
            '    INCLUDE_DIRECTORIES "${ISOSPIN_SC_STATIC_DIR}/include"',
            f'    COMPILE_DEFINITIONS "SC_FAUST_PREFIX=\\"{u["prefix"]}\\"")',
        ]
    for n in natives:
        for rel in native_sources(n):
            lines += [
                f'set_source_files_properties("${{ISOSPIN_SC_STATIC_DIR}}/src/{n["name"]}/{rel}" PROPERTIES',
                f'    INCLUDE_DIRECTORIES "${{ISOSPIN_SC_STATIC_DIR}}/include;${{ISOSPIN_SC_STATIC_DIR}}/src/{n["name"]}")',
            ]
    return "\n".join(lines) + "\n"


def header_file(ugens: list[dict], natives: list[dict], label: str) -> str:
    lines = [
        f"// {GENERATED}",
        f"// The load functions of the static SuperCollider UGens of isospin {label}.",
        "// Call Isospin_Load() once from the server's plugin initialisation.",
        "#pragma once",
        "",
        "struct InterfaceTable;",
        "",
        "// The Faust supercollider.cpp architecture declares the load functions",
        "// with C linkage.",
        'extern "C" {',
    ]
    lines += [f"void {u['class']}_Load(InterfaceTable* table);" for u in ugens]
    lines += ["}"]
    if natives:
        lines += ["", "// The hand-written UGens declare their load functions with C++ linkage."]
        lines += [f"void {n['load']}(InterfaceTable* table);" for n in natives]
    lines += ["", "static inline void Isospin_Load(InterfaceTable* table) {"]
    lines += [f"    {u['class']}_Load(table);" for u in ugens]
    lines += [f"    {n['load']}(table);" for n in natives]
    lines += ["}"]
    return "\n".join(lines) + "\n"


def normalize_name(name: str) -> str:
    """The unit name that the supercollider.cpp architecture makes from the
    Faust name: each word capitalised, without "_", "-" and " ", at most 30
    characters (the same as normalizeClassName in supercollider.cpp)."""
    out, up = "", True
    for char in name:
        if char in "_- ":
            up = True
        elif up:
            out, up = out + char.upper(), False
        else:
            out += char
    return out[:30]


def sc_number(value: float) -> str:
    """A number in sclang syntax, without a ".0" on whole numbers."""
    value = float(value)
    return str(int(value)) if value.is_integer() else repr(value)


def sc_argument(label: str) -> str:
    """The class argument name for a Faust control label (the same rule as
    faust2sc.py): without the characters "\\-_/()[]^", in lower case,
    spaces as "_"."""
    for char in "\\-_/([^)]*)":
        label = label.replace(char, "")
    return label.lower().replace(" ", "_")


def class_file(info: dict, prefix: str) -> tuple[str, str]:
    """The unit name and the SuperCollider class file for one UGen, from the
    Faust JSON description. The class arguments are the audio inputs
    (in0, in1, ...) and then the controls, in the order of the JSON file.
    This is the order in which the UGen reads its inputs."""
    unit = (prefix + normalize_name(info["name"]))[:30]
    (group,) = info["ui"]
    controls = []
    for item in group["items"]:
        if "items" in item:
            sys.exit(f"{info['name']}: a UI group in a group is not supported; "
                     "make the controls of the top group flat")
        controls.append((sc_argument(item["label"]), sc_number(item.get("init", 0))))
    inputs = [f"in{i}" for i in range(info["inputs"])]
    names = ", ".join(inputs + [name for name, _ in controls])
    args = ", ".join(inputs + [f"{name}({default})" for name, default in controls])
    outputs = info["outputs"]

    lines = [
        f"// {GENERATED}",
        f"// The class of the {unit} UGen, made from the Faust description of",
        f"// {info['filename']}.",
        f"{unit} : {'MultiOutUGen' if outputs > 1 else 'UGen'} {{",
        f"    *ar {{ |{args}|",
        f"        ^this.multiNew('audio', {names})",
        "    }",
        "",
        f"    *kr {{ |{args}|",
        f"        ^this.multiNew('control', {names})",
        "    }",
        "",
        f'    name {{ ^"{unit}" }}',
        "",
        '    info { ^"Generated with Faust" }',
    ]
    if info["inputs"] > 0:
        lines += [
            "",
            "    checkInputs {",
            "        if(rate == 'audio') {",
            f"            {info['inputs']}.do {{ |i|",
            "                if(inputs.at(i).rate != 'audio') {",
            "                    ^(\" input at index \" ++ i ++ \" (\" ++ inputs.at(i) ++ \") is not audio rate\")",
            "                };",
            "            };",
            "        };",
            "        ^this.checkValidInputs",
            "    }",
        ]
    if outputs > 1:
        lines += [
            "",
            "    init { |... theInputs|",
            "        inputs = theInputs;",
            f"        ^this.initOutputs({outputs}, rate)",
            "    }",
        ]
    lines += ["}"]
    return unit, "\n".join(lines) + "\n"


